# backend/db/__init__.py
# WHY THIS FILE EXISTS:
#   This empty file tells Python that the "db" folder is a package,
#   so other files can import from it, e.g.:
#       from db.candidates import save_candidate
#       from db.connection import candidates, jobs
#
#   Without this file, those imports fail with ModuleNotFoundError.
#   It intentionally contains no code — its presence is the point.
